// EzVisa service worker: shows Web Push notifications and opens the dashboard on click.
// It does not cache anything, so the dashboard always loads fresh from the server.

self.addEventListener("install", () => {
  self.skipWaiting();
});

self.addEventListener("activate", (event) => {
  event.waitUntil(self.clients.claim());
});

self.addEventListener("push", (event) => {
  let message = {};
  try {
    message = event.data ? event.data.json() : {};
  } catch {
    message = { body: event.data ? event.data.text() : "" };
  }
  event.waitUntil(
    self.registration.showNotification(message.title || "EzVisa", {
      body: message.body || "",
      tag: message.tag,
      icon: "/icon.svg",
      badge: "/icon.svg",
      data: { url: message.url || "/" },
    }),
  );
});

self.addEventListener("notificationclick", (event) => {
  event.notification.close();
  const url = new URL(event.notification.data?.url || "/", self.location.origin).href;
  event.waitUntil(
    self.clients.matchAll({ type: "window", includeUncontrolled: true }).then((windows) => {
      // Links elsewhere (a conversation in Chatwoot) open beside the dashboard, not over it.
      if (!url.startsWith(self.location.origin)) return self.clients.openWindow(url);
      const open = windows.find((w) => w.url.startsWith(self.location.origin));
      if (open) return open.focus().then((w) => w.navigate(url));
      return self.clients.openWindow(url);
    }),
  );
});
